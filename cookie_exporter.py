#!/usr/bin/env python3
"""Keep a yt-dlp compatible Netscape cookies file up to date.

Polls the local Chromium DevTools endpoint (CDP) on a timer, pulls the full
cookie jar via Storage.getCookies, fingerprints it, and atomically rewrites
the output file only when the cookie set actually changed.

The browser profile lives on a persistent volume, so the login survives
container restarts; this exporter is what turns the live cookie jar into a
file yt-dlp services can consume.
"""

import json
import os
import sys
import time
import urllib.request

import websocket  # websocket-client

CDP_HOST = os.environ.get("CDP_HOST", "127.0.0.1")
CDP_PORT = int(os.environ.get("CDP_PORT", "9222"))
OUT_PATH = os.environ.get("COOKIES_FILE", "/data/cookies.txt")
POLL_SECONDS = int(os.environ.get("COOKIE_POLL_INTERVAL", "30"))


def log(msg: str) -> None:
    print(f"[cookie-exporter {time.strftime('%Y-%m-%d %H:%M:%S')}] {msg}", flush=True)


def http_json(url: str) -> dict:
    with urllib.request.urlopen(url, timeout=10) as resp:
        return json.load(resp)


def cdp_call(ws, msg_id: int, method: str, params: dict | None = None) -> dict:
    ws.send(json.dumps({"id": msg_id, "method": method, "params": params or {}}))
    while True:
        msg = json.loads(ws.recv())
        if msg.get("id") == msg_id:
            if "error" in msg:
                raise RuntimeError(f"CDP error for {method}: {msg['error']}")
            return msg.get("result", {})


def fetch_cookies() -> list:
    version = http_json(f"http://{CDP_HOST}:{CDP_PORT}/json/version")
    ws = websocket.create_connection(
        version["webSocketDebuggerUrl"], timeout=15, origin=""
    )
    try:
        result = cdp_call(ws, 1, "Storage.getCookies")
    finally:
        ws.close()
    return result.get("cookies", [])


def cookie_fingerprint(cookies: list) -> str:
    """Stable fingerprint of the cookie set (order-independent)."""
    items = sorted(
        (
            c.get("domain", ""),
            c.get("path", ""),
            c.get("name", ""),
            c.get("value", ""),
            int(c.get("expirationDate") or 0),
            bool(c.get("secure")),
            bool(c.get("hostOnly")),
        )
        for c in cookies
    )
    return json.dumps(items)


def to_netscape(cookies: list) -> str:
    lines = [
        "# Netscape HTTP Cookie File",
        "# https://curl.se/docs/http-cookies.html",
        "# This file was generated by ytcookies. Do not edit.",
        "",
    ]
    for c in cookies:
        domain = c.get("domain", "")
        host_only = bool(c.get("hostOnly"))
        if host_only:
            dom = domain.lstrip(".")
            sub_domains = "FALSE"
        else:
            dom = domain if domain.startswith(".") else "." + domain
            sub_domains = "TRUE"
        expires = c.get("expirationDate") or 0
        exp = int(expires) if expires and expires > 0 else 0  # 0 = session cookie
        name = str(c.get("name", "")).replace("\r", "\\r").replace("\n", "\\n")
        value = str(c.get("value", "")).replace("\r", "\\r").replace("\n", "\\n")
        lines.append(
            "\t".join(
                [
                    dom,
                    sub_domains,
                    c.get("path", "/"),
                    "TRUE" if c.get("secure") else "FALSE",
                    str(exp),
                    name,
                    value,
                ]
            )
        )
    return "\n".join(lines) + "\n"


def atomic_write(path: str, content: str) -> None:
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(content)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)


def main() -> None:
    log(f"starting: cdp={CDP_HOST}:{CDP_PORT} out={OUT_PATH} poll={POLL_SECONDS}s")
    last_fp = None
    while True:
        try:
            cookies = fetch_cookies()
            fp = cookie_fingerprint(cookies)
            if fp != last_fp:
                atomic_write(OUT_PATH, to_netscape(cookies))
                yt = sum(1 for c in cookies if "youtube.com" in (c.get("domain") or ""))
                log(f"cookies exported: {len(cookies)} total ({yt} youtube.com)")
                last_fp = fp
            time.sleep(POLL_SECONDS)
        except KeyboardInterrupt:
            raise
        except Exception as exc:
            log(f"export failed (will retry in {POLL_SECONDS}s): {exc}")
            time.sleep(POLL_SECONDS)


if __name__ == "__main__":
    main()
